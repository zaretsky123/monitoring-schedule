import assert from "node:assert/strict";
import { RECOVERY_STORAGE_KEY, preserveRecoveryCopy, recoveryCopies, sameSnapshot, readCloudBase, writeCloudBase } from "../public/workers/recovery.js";

const values = new Map();
const storage = { getItem: (key) => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const draft = { version: 1, employees: [{ id: "person", name: "Сотрудник" }], selectedMonthKey: "2026-10", months: { "2026-10": { status: "draft", schedule: [{ id: "shift", employeeId: "person" }], draftAbsences: [{ employeeId: "person" }] } } };
preserveRecoveryCopy(storage, draft, "Before cloud load");
assert.deepEqual(recoveryCopies(storage)[0].payload, draft);
preserveRecoveryCopy(storage, draft, "Same state again");
assert.equal(recoveryCopies(storage).length, 1);
draft.months["2026-10"].schedule[0].employeeId = "another";
preserveRecoveryCopy(storage, draft, "Before clearing");
assert.equal(recoveryCopies(storage)[0].payload.months["2026-10"].schedule[0].employeeId, "person", "Stored backup is independent of later editing");
assert.equal(recoveryCopies(storage).length, 2);
const before = storage.getItem(RECOVERY_STORAGE_KEY);
assert.throws(() => preserveRecoveryCopy({ getItem: storage.getItem, setItem() { throw new Error("QuotaExceededError"); } }, { ...draft, selectedMonthKey: "2026-11" }, "Cannot store"));
assert.equal(storage.getItem(RECOVERY_STORAGE_KEY), before, "Failure never deletes existing recovery data");
storage.setItem(RECOVERY_STORAGE_KEY, "broken");
assert.throws(() => preserveRecoveryCopy(storage, draft, "Do not overwrite corrupt recovery storage"));
assert.equal(storage.getItem(RECOVERY_STORAGE_KEY), "broken");
storage.setItem(RECOVERY_STORAGE_KEY, before);
for (let n = 0; n < 25; n++) preserveRecoveryCopy(storage, { ...draft, marker: n }, "No pruning");
assert.equal(recoveryCopies(storage).length, 27, "Older unsynced copies are not automatically pruned");
assert.equal(sameSnapshot({ employees: [{ id: "one", name: "Иван" }], months: {} }, { months: {}, employees: [{ name: "Иван", id: "one" }] }), true, "Object key ordering is not a data conflict");
assert.equal(sameSnapshot({ employees: [{ id: "one" }] }, { employees: [{ id: "two" }] }), false);
writeCloudBase(storage, "workspace", draft);
assert.deepEqual(readCloudBase(storage, "workspace"), draft);
assert.equal(readCloudBase(storage, "other-workspace"), null);
assert.equal(sameSnapshot(readCloudBase(storage, "workspace"), { ...draft, selectedMonthKey: "2026-11" }), false, "Unsynced local edits are distinguishable from unchanged cache");
console.log("Recovery: full employee/month/draft preservation, independent copies, deduplication, quota failure, corrupt storage and no automatic pruning passed.");
